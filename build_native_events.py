"""Compile the bundled Windows observer; never load it into Helldivers.

Requires Zig 0.13.0 (zig cc), supplied with --zig.
The mod builder embeds the result; players do not install another dependency.
"""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent
NATIVE = ROOT / 'native'
SOURCES = ('weaponflow_events.c',)
NATIVE_SOURCES = ('weaponflow_events.c','weaponflow_events.h','events_anchors.h')


def source_digest(directory=NATIVE):
    digest = hashlib.sha256()
    digest.update(b'build_native_events.py\0'+(directory.parent/'build_native_events.py').read_bytes())
    for name in sorted(NATIVE_SOURCES):
        digest.update(name.encode() + b'\0' + (directory/name).read_bytes())
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--zig', required=True, type=Path)
    parser.add_argument('--test', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'analysis/events-native-20261017' if args.test else NATIVE / 'bin'
    target.mkdir(parents=True, exist_ok=True)
    dll = target / ('weaponflow-events-test.dll' if args.test else 'weaponflow-events.dll')
    zig_lib = args.zig.resolve().parent / 'lib'
    with tempfile.TemporaryDirectory(prefix='weaponflow-events-build-') as temporary:
        command = [str(args.zig), 'cc', '-target', 'x86_64-windows-gnu', '-std=c11',
                   '-O2', '-g0', '-fno-builtin', '-fno-stack-protector', '-fms-extensions',
                   '-shared', '-nostdlib', '-Wl,--entry,DllMain',
                   '-isystem', str(zig_lib/'libc/include/any-windows-any'),
                   '-isystem', str(zig_lib/'include'), '-I', str(NATIVE),
                   *[str(NATIVE / p) for p in SOURCES], '-lkernel32', '-o', str(dll)]
        if args.test:
            command.insert(2, '-DWF_TEST')
        subprocess.run(command, cwd=temporary, check=True)
    data = dll.read_bytes()
    metadata = dict(abi=1, sha256=hashlib.sha256(data).hexdigest(), size=len(data),
                    source_sha256=source_digest(), compiler='Zig 0.13.0 / Clang',
                    backend='game-api-notifications')
    dll.with_suffix('.json').write_text(json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
    if not args.test:
        chunks = [data[i:i+2048].hex() for i in range(0,len(data),2048)]
        lua = ('-- Generated by build_native_events.py. Original native source is in native/.\n'
               '-- Game-owned writable API slots; original code pages are untouched.\n'
               f'return {{abi=1, sha256="{metadata["sha256"]}", '
               f'source_sha256="{metadata["source_sha256"]}", hex=\n' +
               '..\n'.join('"'+chunk+'"' for chunk in chunks) + '}\n')
        (ROOT / 'src/native_weapon_events_payload.lua').write_text(lua, encoding='utf-8')
    print(json.dumps(metadata))


if __name__ == '__main__':
    main()
